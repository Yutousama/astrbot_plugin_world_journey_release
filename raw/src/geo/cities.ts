/**
 * 内置城市表 —— 这个扩展的**事实底座**。
 *
 * 为什么内置而不实时查高德：旅行的时长、时区、有没有港口，都要在**没有网络**的时候
 * 也算得出来。半年连续旅行天天调接口，个人开发者的配额几天就烧完，而配额一没，
 * 表现不是报错，是「她开始随机乱走」。所以底座写死在代码里，高德只做天气这类
 * 每天一次的可选补充。
 *
 * ## 坐标的精度要求
 * 只用来算距离（Haversine），小数点后两位就够 —— 0.01 度约 1.1 公里，在「火车开多久」
 * 这个尺度上完全可以忽略。所以这里的坐标不追求测绘级，追求**城市不搞错**。
 * 真正要紧的是两个布尔：有没有机场、有没有码头。这两个错了，她就会「从兰州坐船出发」。
 *
 * ## tags 是给谁看的
 * 给她挑目的地、也给她写景色。**不是景点的完整清单** —— 那是百科全书的事。
 * 这里只标「这个城市是什么路数」，比如「山」「海」「古城」，用来让她避开「又去一个山城」。
 */

/**
 * 一个地点占多久。**默认半天**（一天排两个），`（整天）`占一天，`（2 天）`占两天。
 *
 * 2026-11-01 Mr.Q 在同步表里把黄山拆成「黄山风景区1」「黄山风景区2」——
 * 那是拿格子硬凑"要爬两天"。这个后缀就是给这件事一个正经写法，
 * 存进代码也只留真名，不会让她念出「今天去黄山风景区1」。
 */
export function spotDays(raw: string): number {
  const m = /[（(]\s*(整天|(\d+(?:\.\d+)?)\s*天)\s*[）)]$/.exec(raw);
  if (!m) return 0.5;
  return m[1] === '整天' ? 1 : Number(m[2]);
}

/** 去掉天数后缀，只留地名。 */
export function spotName(raw: string): string {
  // 半角括号也认 —— 在表格里手打「(2 天)」比全角顺手，不能因此失效
  return raw.replace(/[（(]\s*(整天|(\d+(?:\.\d+)?)\s*天)\s*[）)]$/, '').trim();
}

/**
 * 展开成「半天槽」序列 —— 一天两格。
 *
 * `['黄山风景区（2 天）', '宏村']` → `['黄山风景区','黄山风景区','黄山风景区','黄山风景区','宏村']`
 *
 * 同一天里两格是同一个名字 → `planDay` 会合并成一条「一整天都在……」，
 * 不会上午说一遍、下午再说一遍。
 */
export function expandSlots(spots: readonly string[]): string[] {
  const out: string[] = [];
  for (const raw of spots) {
    const n = Math.max(1, Math.round(spotDays(raw) * 2));
    const name = spotName(raw);
    for (let i = 0; i < n; i++) out.push(name);
  }
  return out;
}

/** 当地在某个月才有的事。`months` 用公历月份（1-12）。 */
export interface Festival {
  readonly name: string;
  readonly months: readonly number[];
  /** 一句话说那时候街上是什么样。别写成旅游宣传语。 */
  readonly what: string;
}

export interface City {
  readonly id: string;
  readonly name: string;
  /** 省 / 州 / 大区。国外就是国家名。 */
  readonly region: string;
  readonly country: 'CN' | 'JP' | 'KR' | 'TH' | 'SG' | 'VN' | 'FR' | 'GB' | 'IT' | 'RU' | 'US' | 'AU' | 'NZ' | 'AE' | 'TR' | 'BR' | 'AR' | 'CA' | 'MX';
  readonly lat: number;
  readonly lon: number;
  /** IANA 时区。当地时间一律按它算，不靠 UTC 偏移硬编码 —— 夏令时会错。 */
  readonly tz: string;
  readonly air: boolean;
  readonly rail: boolean;
  /** 有客运码头（海港或长江/珠江航道）。坐船的必要条件。 */
  readonly port: boolean;
  readonly tags: readonly string[];
  /**
   * 真实地标，2-3 个。
   *
   * **为什么必须有这一项**：只有 tag（「山」「古城」）和「吃什么方向」的时候，
   * 她写日记能写出「服务区那碗面」，写景只能写「在街上走」—— 因为景没有素材，
   * 而提示词又不许她编不存在的地方。两头一夹，整篇就变成吃播。
   *
   * 只填**有把握真实存在**的。填不出的城市宁可留空，用 tag 生成泛化说法
   * （「城外的山」），也不要瞎编一个名字 —— 那是她最容易被抓到的地方。
   */
  readonly spots: readonly string[];
  /**
   * **只有夜里才成立的去处。空 = 这天晚上没什么非做不可的，那就回酒店。**
   *
   * 2026-11-01 Mr.Q：晚上也该有活动，**但当地没什么必须晚上干的那就别硬凑**。
   * 「敦煌鸣沙山晚上的万人合唱」「青岛晚上赶海」「兰州正宁路夜市」这种才算。
   *
   * 以前这一格是靠 `tags` 拼出来的（有「古城」就写「在亮灯的老街上走」），
   * 于是每座城市**都有一条** —— 泛、假、而且跟白天那条老街重复。
   */
  /**
   * `spots` 展开成半天槽之后的结果。**排期按这个取，不按 spots 取。**
   *
   * 一个地点标了（2 天）就会在这里出现四格，于是连续两天都是它。
   */
  readonly slots: readonly string[];
  readonly night: string | null;
  /**
   * 当地在某个时节才有的东西。`null` = 没有，不排。
   *
   * 带月份而不是日期：泼水节、宋干节这种是公历固定的，但雪顿节、三月街按藏历农历走，
   * 年年不一样，写死日期一定出错。给月份，文案就说「这个月」，错了也不算说错。
   */
  readonly festival: Festival | null;
  /**
   * 住宿价格指数。`1.0` = 中国普通地级市（成都那档）。
   *
   * **不填这个字段的时候，她在纽约和在天水住一样的价钱。**
   * 2026-10-31 实测：三档房的价格是写死的（景观 680 / 普通 220 / 差店 60），
   * 于是「纽约，改造的老宅，750 元」—— 而纽约五星实测中位是 8,656。
   *
   * 校准依据是一份 37 城实测数据（2026-11-10 入住一晚、含税、人民币中位），
   * 五星价除以成都的 780 得到系数。只影响「住一晚多少钱」，不影响别的。
   */
  readonly priceIdx: number;
}

