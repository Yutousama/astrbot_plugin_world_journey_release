const BY_ID = new Map(CITIES.map((c) => [c.id, c]));

/** 按 id 取。没有就返回 null —— 调用方必须处理"不认识的城"，别拿默认值顶。 */
export function cityById(id: string): City | null {
  return BY_ID.get(id.trim().toLowerCase()) ?? null;
}

/** 按名字找。中文名优先，其次英文 id。找不到返回 null。 */
export function cityByName(name: string): City | null {
  const key = name.trim();
  if (!key) return null;
  const lower = key.toLowerCase();
  const byId = BY_ID.get(lower);
  if (byId) return byId;
  for (const c of CITIES) {
    if (c.name === key) return c;
  }
  // 「北京市」「兰州市」这种带后缀的也认，去掉尾字再试一次。
  const stripped = key.replace(/市$|地区$|特别行政区$/, '');
  if (stripped !== key) {
    for (const c of CITIES) {
      if (c.name === stripped) return c;
    }
  }
  return null;
}

/** 国内 / 国外。国外才有时差，也才需要护照这件事出现在叙事里。 */
export function isForeign(c: City): boolean {
  return c.country !== 'CN';
}
